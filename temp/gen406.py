for r in D:
    for i, s in enumerate(r["steps"]):
        if len(s["t"]) < 21: probs.append((r["id"], "text短", i, len(s["t"]), s["t"]))
        if len(s["tip"]) < 17: probs.append((r["id"], "tip短", i, len(s["tip"]), s["tip"]))
        if len(s["cue"]) < 10: probs.append((r["id"], "cue短", i, len(s["cue"]), s["cue"]))
    tot = sum(s["time"] for s in r["steps"])
    if tot > r["prep"] + r["cook"]: probs.append((r["id"], "时长超", tot, r["prep"] + r["cook"]))
    for k, mn in (("tips", 15), ("mistakes", 15), ("variations", 17)):
        if len(r[k]) < 3: probs.append((r["id"], k + "条数少", len(r[k])))
        for s in r[k]:
            if len(s) < mn: probs.append((r["id"], k + "短", len(s), s))
    for k, mn in (("origin", 46), ("serving", 20), ("storage", 20)):
        if len(r[k]) < mn: probs.append((r["id"], k + "短", len(r[k]), r[k]))
    for s in r["safety"]:
        if len(s) < 15: probs.append((r["id"], "safety短", len(s)))
    for g in r["ingredients"]:
        for it in g["items"]:
            if len(it["note"]) < 2: probs.append((r["id"], "note短", it["n"], it["note"]))
    main = [it for g in r["ingredients"] if g["group"] == "main" for it in g["items"]]
    per = sum(it["a"] for it in main) / r["servings"]
    if per < 60: probs.append((r["id"], "主料每份不足", per))

