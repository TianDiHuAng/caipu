ITEMS = json.loads((ROOT / "data/ingredients.json").read_text(encoding="utf-8-sig"))["items"]

IDX = {}
for it in ITEMS:
    for k in [it["zh"]] + it.get("aliases", []):
        IDX.setdefault(k, []).append(it)


def allergens_of(names):
    out = []
    for n in names:
        hits = IDX.get(n) or []
        if len(hits) != 1:
            raise SystemExit(f"食材无法唯一命中词典: {n} -> {[h['key'] for h in hits]}")
        for a in hits[0]["allergens"]:
            if a not in out:
                out.append(a)
    return sorted(out)


def build(r):
    groups = []
    names = []
    for g in ("main", "aux", "seasoning"):
        rows = r["ingredients"].get(g) or []
        if not rows:
            continue
        items = []
        for row in rows:
            name, name_en, amount, unit, note = row[0], row[1], row[2], row[3], row[4]
            optional = row[5] if len(row) > 5 else False
            items.append({"name": name, "name_en": name_en, "amount": amount,
                          "unit": unit, "note": note, "optional": optional})
            names.append(name)
        groups.append({"group": g, "items": items})

    steps = []
    for i, s in enumerate(r["steps"], 1):
        steps.append({"n": i, "text": s[0], "time_min": s[1], "heat": s[2],
                      "tip": s[3], "visual_cue": s[4]})

    doc = {
        "schema_version": "1.0",
        "content_version": 1,
        "id": r["id"],
        "name": r["name"],
        "cuisine": r["cuisine"],
        "category": r["category"],
        "difficulty": r["difficulty"],
        "time": r["time"],
        "servings": r["servings"],
        "flavor": r["flavor"],
        "ingredients": groups,
        "equipment": r["equipment"],
        "steps": steps,
        "tips": r["tips"],
        "common_mistakes": r["common_mistakes"],
        "substitutions": [{"original": a, "substitute": b, "ratio": c, "note": d}
                          for a, b, c, d in r["substitutions"]],
        "variations": r["variations"],
        "serving_suggestion": r["serving_suggestion"],
        "storage": r["storage"],
        "nutrition_estimate": r["nutrition_estimate"],
        "allergens": allergens_of(names),
        "diet_tags": r.get("diet_tags", []),
        "food_safety_notes": r["food_safety_notes"],
        "origin_note": r["origin_note"],
        "tags": r["tags"],
        "related_ids": r["related_ids"],
        "image_url": None,
        "image_credit": None,
        "status": "published",
        "created_at": "2026-11-18",
        "updated_at": "2026-11-18",
    }
    out = ROOT / "data/recipes" / r["cuisine"]["region"] / r["cuisine"]["style"] / f"{r['id']}.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(doc, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return out


